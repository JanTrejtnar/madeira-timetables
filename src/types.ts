export type DayKey = 'weekday' | 'saturday' | 'sunday' | 'weekday_school' | 'weekday_holiday';

export interface Departure {
  t: string; // "HH:MM"; times after midnight (e.g. 00:10) follow late-evening ones in the list
  notes?: string[];
}

export interface Stop {
  code: string | null;
  name: string;
  lat?: number;
  lon?: number;
  /** coordinates were not printed with the timetable but matched by name against a stop of another route */
  approx?: boolean;
  /** position interpolated along the route polyline between two stops with known positions (build:data) */
  isEstimatedLocation?: boolean;
  /**
   * How trustworthy the position is: exact = official stop (SIGA / GTFS / OSM bus stop); interpolated = evenly spaced on the route
   * polyline; settlement_center = centre of the village the stop is named after (platform not verified);
   * name_match = taken from a stop of the same name on another route.
   */
  locationPrecision?: 'exact' | 'interpolated' | 'settlement_center' | 'name_match';
  /** not a stop of the timetable: a "Via X" place inserted for the selected trip (position estimated, time interpolated) */
  via?: boolean;
  /** id of the Funchal terminal the stop belongs to (data/stop-overrides.json funchalTerminals): stops of two terminals are never one node */
  terminal?: string;
  /** Municipality (concelho) of the stop, set by build:data */
  muni?: string;
  /** Parish (freguesia) of the stop, set by build:data; "Name, Municipality" where the name exists twice */
  par?: string;
}

/** One run of a bus: a time at every stop (null = does not call there). */
export interface Trip {
  days: DayKey[];
  times: (string | null)[];
  notes?: string[];
}

export interface Direction {
  variant: string | null;
  /** Terminal the departures below leave from (as printed in the timetable header). */
  from: string | null;
  to: string;
  shapeId: number | null;
  /** 'osrm': the polyline was generated by the OSRM road router through the stops (no SIGA geometry) */
  shapeSource?: 'osrm';
  stopSource: 'shapedata' | 'pdf' | 'none';
  stops: Stop[];
  /** Departures from the first stop (terminal). */
  departures: Partial<Record<DayKey, Departure[]>>;
  /** Times at every stop; only for timetables that print them ("Locais Passagem"). */
  trips?: Trip[];
  /** true: times at stops after the first are estimates (distance / average speed); false: printed in the timetable. */
  isEstimated?: boolean;
  /** the timetable prints no stop list: the stops are the two terminals (data/terminals.json), the times at the far end are estimated */
  terminalsOnly?: boolean;
  /** the intermediate stops and running times come from the SIGA journey planner (data/siga-patterns.json), not from the timetable */
  enrichedFrom?: 'siga-planner';
  /** Estimated minutes from the first stop and km along the route, one per stop (only when isEstimated). */
  stopOffsets?: number[];
  stopKm?: number[];
  speedKmh?: number;
}

export interface Line {
  id: number;
  number: string;
  newNumber: string | null;
  oldNumber: string;
  name: string;
  route: string;
  municipality: string | null;
  type: 'urbano' | 'interurbano';
  /** same as type === 'interurbano'; set by build:data (also for urban-labelled lines that span municipalities / > 15 km) */
  isInterurbano?: boolean;
  /** why build:data changed the type printed by SIGA */
  typeReason?: string;
  /** the type printed by SIGA when build:data overrode it */
  typeSiga?: 'urbano' | 'interurbano';
  pdfUrl: string;
  pdfLocal?: string;
  jpgUrl: string | null;
  family: string;
  hasParsedSchedule: boolean;
  notes: Record<string, string>;
  generalNotes?: string[];
  dayLabels?: Partial<Record<DayKey, string>>;
  directions: Direction[];
  /** "Via X" notes (key = legend code, or the note text itself in hand-made transcriptions) -> the places the trip calls at, in printed order; `after[dirIndex]` = index of the stop each follows */
  via?: Record<string, ViaPlace[]>;
  /** road route through the via places of a stretch, key `note|dirIndex|stopIndex` (build:data): replaces the polyline between a and b on the map */
  viaRoutes?: Record<string, ViaRoute>;
  /** operator outside SIGA (e.g. Horários do Funchal) and where its timetable was read */
  operator?: string;
  sourceUrl?: string;
  /** prices and conditions shown on the line page, per UI language */
  info?: { price?: Record<'cs' | 'en' | 'pt', string>; conditions?: Record<'cs' | 'en' | 'pt', string> };
}

export interface ViaRoute {
  /** the polyline points the route replaces between (nearest points) */
  a: [number, number];
  b: [number, number];
  pts: [number, number][];
}

export interface ViaPlace {
  name: string;
  lat: number;
  lon: number;
  source: 'osm' | 'manual';
  after: Record<number, number>;
  /** position along the route polyline per direction (index of its nearest point): places after the same stop are shown in this order */
  at?: Record<number, number>;
  /** municipality and parish of the place (build:data), so the planner groups it with the stops of its parish */
  muni?: string;
  par?: string;
}

export interface Dataset {
  generatedAt: string;
  source: string;
  lines: Line[];
  /** guaranteed walking links between the Funchal terminals (minutes), see data/stop-overrides.json */
  terminalWalks?: { a: string; b: string; min: number }[];
}

/** One route drawn on the map: the shape polyline (if any) plus its stops. */
/** A point the user picked on the map (planner "Pick on map") and the stop it was assigned to. */
export interface MapPin {
  kind: 'from' | 'to';
  /** tooltip text ("Start", "Destination" ...); default: the picked-point wording */
  label?: string;
  lat: number;
  lon: number;
  stop?: { lat: number; lon: number; name: string };
  /** walking route along the streets from the pin to its stop (or back), [lat, lon]; without it a straight dashed line is drawn */
  path?: [number, number][];
}

export interface MapLayer {
  shapeId: number | null;
  stops: Stop[];
  color: string;
  /** a connection with a transfer: this bus in the map legend (line number and where it is ridden) */
  legend?: { badge: string; text: string };
  /** road routes through "Via" places of the drawn trip, spliced into the shape */
  detours?: ViaRoute[];
  /** planner leg: only the stretch from stop `from` to stop `to` of `stops` is drawn in full colour, the rest of the line faintly (`stops` = every stop of the trip, [lat, lon]) */
  ride?: { stops: ([number, number] | null)[]; from: number; to: number };
  /** every stop of the drawn trip with a position, in order, and whether the trip calls there: the polyline does not drive into a side road to a stop it skips */
  trip?: { stops: { at: [number, number]; calls: boolean }[] };
  /** places where the traveller changes buses: the alighting stop, and the boarding stop of the next bus when it is another one (walk between them) */
  transfers?: { name: string; at: [number, number]; to?: [number, number]; /** walking route between the two platforms along the streets */ path?: [number, number][] }[];
  /** picked start / destination points drawn as red pins with a dashed line to their stop */
  pins?: MapPin[];
}

/** Stop of the first map layer to centre on and open the popup of, with the passing time of the selected trip. */
export interface MapFocus {
  stopIndex: number;
  /** changes on every tap so the popup re-opens even for the same stop */
  seq: number;
  /** the stop was clicked on the map itself: highlight it, but do not fly there / reopen the popup */
  fromMap?: boolean;
  /** one display string per stop of the layer ("11:18", "~11:18" or null) */
  times: (string | null)[];
}
