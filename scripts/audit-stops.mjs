// Audit of stop positions after build:data: writes data/missing-stops.json with
//  - stops without any coordinates (not on the map, no route through them),
// Both lists are sorted by priority: the number of lines that serve the stop, then the number of trips that call at it (most affected first).
//  - stops whose position is only an estimate (settlement centre, interpolated along the route, taken by name from another route).
// The report is regenerated from public/data/schedules.json on every run (and by build:data), so a stop that gets coordinates
// (data/stop-overrides.json) leaves the list by itself on the next `npm run build:data`.
import { readFileSync, writeFileSync } from 'node:fs';

const schedules = JSON.parse(readFileSync('public/data/schedules.json', 'utf8'));
const missing = new Map();
const estimated = new Map();

/** trips of a direction: the printed trips, else its departures */
const tripsOf = (d) => d.trips?.length ?? Object.values(d.departures ?? {}).reduce((n, v) => n + (v?.length ?? 0), 0);

const add = (map, s, line, status, d) => {
  const e = map.get(s.name) ?? { name: s.name, code: s.code ?? null, status, lines: new Set(), trips: 0 };
  e.lines.add(line.number ?? line.id);
  e.trips += tripsOf(d);
  map.set(s.name, e);
};

for (const line of schedules.lines) {
  for (const d of line.directions) {
    for (const s of d.stops) {
      if (s.via) continue;
      if (s.lat === undefined || s.lon === undefined) add(missing, s, line, 'no coordinates', d);
      else if (s.locationPrecision && s.locationPrecision !== 'exact') add(estimated, s, line, s.locationPrecision, d);
      else if (s.isEstimatedLocation || s.approx) add(estimated, s, line, s.isEstimatedLocation ? 'interpolated' : 'name_match', d);
    }
  }
}

const list = (map) =>
  [...map.values()]
    .map((e) => ({ name: e.name, code: e.code, status: e.status, lineCount: e.lines.size, tripCount: e.trips, lines: [...e.lines].sort() }))
    .sort((a, b) => b.lineCount - a.lineCount || b.tripCount - a.tripCount || a.name.localeCompare(b.name));
const report = {
  _comment: 'Generated by scripts/audit-stops.mjs (build:data), sorted by priority (lineCount, then tripCount: trips in the directions that call at the stop). Add coordinates to data/stop-overrides.json and run `npm run build:data`: the stop drops out of this list.',
  missing: list(missing),
  estimated: list(estimated),
};
writeFileSync('data/missing-stops.json', JSON.stringify(report, null, 2) + '\n');
console.log(`stop audit: ${report.missing.length} stops without coordinates, ${report.estimated.length} with an estimated position (data/missing-stops.json)`);
